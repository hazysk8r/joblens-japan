/**
 * ページタイトル(ブラウザのタブ・履歴・読み上げで画面を見分けるための名前)。
 * React 19は描画した<title>を<head>へ移すため、各画面で1つだけ描画する。共通のレイアウトでは描画しない。
 * 画面の名前を先に置き、タブが狭くて途中で切れても見分けられるようにする。
 *
 * 利用者が入力した値(求人のタイトルや会社名、検索語)は載せない。
 * 履歴や入力候補はログアウト後も残り、共用のパソコンでは応募先や転職活動が分かってしまうため。
 */
export default function PageTitle({ name }: { name: string }) {
  return <title>{`${name} | JobLens Japan`}</title>;
}
